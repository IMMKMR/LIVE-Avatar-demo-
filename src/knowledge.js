export function matchKnowledge(queryText, lang = 'hi') {
  const q = (queryText || '').toLowerCase().trim();
  const safeLang = lang === 'en' ? 'en' : 'hi';

  for (const topic of QUICK_TOPICS) {
    if (topic.keywords.some((kw) => q.includes(kw))) {
      return {
        text: topic.answer[safeLang],
        ref: topic.ref,
        category: topic.category,
        title: topic.title,
      };
    }
  }

  if (/^(hi|hello|hey|namaste|नमस्ते|good morning|good afternoon)/i.test(q)) {
    return {
      text: SYSTEM_SCRIPTS[safeLang].welcome,
      ref: 'GAVL-AI',
      category: 'Assistant',
      title: 'Greeting',
    };
  }

  if (/(thank|thanks|धन्यवाद|bye|done|that's all)/i.test(q)) {
    return {
      text: SYSTEM_SCRIPTS[safeLang].closing,
      ref: 'GAVL-AI',
      category: 'Assistant',
      title: 'Wrap-up',
    };
  }

  return {
    text: SYSTEM_SCRIPTS[safeLang].fallback(queryText.trim()),
    ref: 'GAVL-KB-GEN',
    category: 'Internal Desk',
    title: 'General Inquiry',
  };
}
